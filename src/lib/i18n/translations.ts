type DeepWiden<T> = T extends string
  ? string
  : { [K in keyof T]: DeepWiden<T[K]> };

export type TranslationDict = DeepWiden<typeof translations.en>;

/** Like `format`, but placeholder values may be React nodes (e.g. a styled name). */
export function formatNodes(template: string, values: Record<string, ReactNode>): ReactNode {
  return template
    .split(/\{(\w+)\}/)
    .map((part, i) => createElement(Fragment, { key: i }, i % 2 === 1 ? (values[part] ?? `{${part}}`) : part));
}

/** Translated display name for a club/community role stored in English (e.g. "President"). */
export function roleLabel(role: string | null | undefined, t: TranslationDict): string {
  if (!role) return "";
  return (t.dashboard.roles as Record<string, string>)[role] ?? role;
}

/** Fills `{name}` placeholders in a translation string. */
export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}
